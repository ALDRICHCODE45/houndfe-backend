export type CashRuleCode =
  (typeof CASH_RULE_CODES)[keyof typeof CASH_RULE_CODES];

/** Build the standard violation for a cash-register rule. */
export function cashRuleViolation(
  code: CashRuleCode,
  message: string,
  details?: Record<string, unknown>,
): BusinessRuleViolationError {
  return new BusinessRuleViolationError(message, code, details);
}
