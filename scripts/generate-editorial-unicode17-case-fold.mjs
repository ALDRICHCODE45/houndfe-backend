import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export const sourceUrl =
  'https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt';
export const sourceSha256 =
  'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183';
const table = new URL(
  '../src/catalog-editorial/domain/editorial-unicode17-case-fold.generated.ts',
  import.meta.url,
);
const license = new URL('../docs/licenses/unicode-3.0.txt', import.meta.url);

export function generate(source) {
  if (createHash('sha256').update(source).digest('hex') !== sourceSha256) {
    throw new Error('CaseFolding.txt SHA-256 mismatch; no writes permitted');
  }
  const entries = [];
  for (const line of source.toString('utf8').split('\n')) {
    const match = /^([0-9A-F]+); ([CF]); ([0-9A-F ]+);/.exec(line);
    if (!match) continue; // S (simple) and T (Turkic) deliberately excluded.
    const point = Number.parseInt(match[1], 16);
    const escaped = match[3]
      .split(' ')
      .map((hex) => `\\u{${Number.parseInt(hex, 16).toString(16)}}`)
      .join('');
    entries.push({ point, escaped });
  }
  if (
    entries.length !== 1585 ||
    new Set(entries.map((e) => e.point)).size !== 1585
  ) {
    throw new Error('Expected exactly 1,585 unique C/F entries');
  }
  entries.sort((a, b) => a.point - b.point);
  return [
    '// Generated by scripts/generate-editorial-unicode17-case-fold.mjs; do not edit.',
    `// Source: ${sourceUrl}`,
    `// SHA-256: ${sourceSha256}`,
    '// Unicode 17.0.0 full default C/F mappings (1,585); excludes S/T.',
    '// License: docs/licenses/unicode-3.0.txt (Unicode License v3).',
    '// prettier-ignore',
    'export const UNICODE17_CASE_FOLD: Readonly<Record<number, string>> = Object.freeze({',
    ...entries.map(
      ({ point, escaped }) => `  0x${point.toString(16)}: '${escaped}',`,
    ),
    '});',
    '',
  ].join('\n');
}

async function fetchBytes(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`Fetch ${url}: ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

async function main() {
  const check = process.argv[2] === '--check';
  if (process.argv.length > (check ? 3 : 2))
    throw new Error('Usage: node script [--check]');
  // Verify source before generating or writing either artifact.
  const generated = generate(await fetchBytes(sourceUrl));
  const licenseBytes = await fetchBytes('https://www.unicode.org/license.txt');
  if (!licenseBytes.toString('utf8').startsWith('UNICODE LICENSE V3')) {
    throw new Error('Expected Unicode License v3 for unicode-3.0.txt');
  }
  if (check) {
    if (
      (await readFile(table, 'utf8')) !== generated ||
      !(await readFile(license)).equals(licenseBytes)
    ) {
      throw new Error('Generated table or exact license bytes differ');
    }
    console.log(
      'PASS: 1,585 C/F mappings, pinned source, table and license byte parity',
    );
  } else {
    await mkdir(new URL('../docs/licenses/', import.meta.url), {
      recursive: true,
    });
    await writeFile(table, generated);
    await writeFile(license, licenseBytes);
    console.log('Generated 1,585 C/F mappings and exact Unicode License v3');
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await main();
}
